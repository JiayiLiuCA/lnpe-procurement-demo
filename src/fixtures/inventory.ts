/** 合同号按「日期 + 供应商」稳定生成：机加工/钣金类用 XY 编号，其余用 SJ 编号 */
const XY_SUPPLIERS = new Set(["嘉信", "宏泰"]);
function contractNoFor(date: string, supplier: string, seqByDay: Map<string, number>): string {
  const day = date.replace(/-/g, "");
  const k = `${day}|${supplier}`;
  if (!seqByDay.has(k)) {
    const used = [...seqByDay.keys()].filter((x) => x.startsWith(`${day}|`)).length + 1;
    seqByDay.set(k, used);
  }
  const seq = seqByDay.get(k)!;
  return XY_SUPPLIERS.has(supplier) ? `LNPE-XY${day}-${String(seq).padStart(2, "0")}` : `LNPE-${day}${String(seq).padStart(3, "0")}-SJ`;
}

export const pastPurchases: PastPurchase[] = (() => {
  const seq = new Map<string, number>();
  const out: PastPurchase[] = [];
  for (const [name, spec, supplier, points] of SERIES) {
    for (const [date, unitPrice, qty] of points) {
      out.push({ name, spec, date, unitPrice, qty, contractNo: contractNoFor(date, supplier, seq), supplier });
    }
  }
  return out.sort((a, b) => a.date.localeCompare(b.date));
})();
